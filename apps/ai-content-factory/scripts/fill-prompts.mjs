// Replaces the placeholder .md stubs in data/assets/prompts/<slot>/ with real,
// edit-ready content. Each file is a long-enough chunk to serve as RAG context
// for Claude, while still being a starting point the owner can rewrite.
//
// Usage (inside the container):
//   docker exec ai-content-factory node /app/scripts/fill-prompts.mjs

import { mkdirSync, readdirSync, unlinkSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = '/app/data/assets/prompts';

function write(slot, body) {
  const dir = join(ROOT, slot);
  mkdirSync(dir, { recursive: true });
  // Wipe any existing placeholder/inline files so this script is idempotent.
  if (existsSync(dir)) {
    for (const f of readdirSync(dir).filter((f) => f.endsWith('.md'))) {
      try { unlinkSync(join(dir, f)); } catch { /* ignore */ }
    }
  }
  writeFileSync(join(dir, `${Date.now()}-content.md`), body, 'utf8');
  console.log(`  ${slot} ← ${body.split('\n').length} lines`);
}

