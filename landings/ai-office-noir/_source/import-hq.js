#!/usr/bin/env node
/*
 * Build assets/data.js from the real hq2 office data (apps/hq-office):
 * office.config.js (departments, heads), agent-content.js (catalog + dossiers), dept-content.js.
 * Re-run after the office changes:  node landings/ai-office-noir/_source/import-hq.js
 */
const fs = require('fs'), path = require('path');
const HQ = path.resolve(__dirname, '../../../apps/hq-office');
global.window = {};
['office.config.js', 'dept-content.js', 'agent-content.js', 'tasks.js', 'tasks.auto.js'].forEach(f => require(path.join(HQ, f)));
const CFG = window.OFFICE_CONFIG, CAT = window.AGENT_CATALOG, AC = window.AGENT_CONTENT, HC = window.HEAD_CONTENT;
const IMG = /\.(jpe?g|png|webp)(\?|$)/i;
const STATUS = { working: 'Работает', thinking: 'Думает', idle: 'Ждёт задачу' };
const SHORT = { ceo: 'Стратегия', marketing: 'Маркетинг', sales: 'Продажи', traffic: 'Реклама' };

const pics = c => (c.results || []).filter(r => r.type === 'gallery' || r.type === 'strips')
  .flatMap(r => r.items || []).map(i => i.src).filter(s => s && IMG.test(s));
const links = list => (list || []).filter(x => x && x.url).slice(0, 8).map(x => ({ title: x.title, url: x.url }));

const items = [];
for (const d of CFG.depts) {
  const h = d.head, hc = HC[d.id] || {};
  items.push({
    id: h.id, name: h.name, role: h.title, group: SHORT[d.id], dept: d.name, kind: 'head',
    img: `img/head-${h.id}.jpg`, tag: 'Руководитель', tagStyle: 'acc',
    meta: [SHORT[d.id], `${d.agents.length} агентов`], price: d.name, sub: h.title.split(' — ')[0],
    about: hc.lead || '', features: hc.zones || [], spec: (hc.process || []).map(s => [s.t, s.d]),
    links: links(hc.materials), nums: [[String(d.agents.length), 'агентов в отделе'], [String((hc.zones || []).length), 'зоны ответственности'], [String((hc.process || []).length), 'шагов процесса']],
    f: { dept: SHORT[d.id], kind: 'Руководители' },
  });
  for (const id of d.agents) {
    const k = CAT[id], c = AC[id] || {}, ov = (CFG.agents || {})[id] || {};
    const g = pics(c).slice(0, 4), sk = c.skills || [];
    items.push({
      id, name: ov.name || k.name, role: ov.role || k.role, group: SHORT[d.id], dept: d.name, kind: 'agent', color: k.color,
      img: `img/agent-${id}.jpg`, gallery: [`img/agent-${id}.jpg`].concat(g),
      tag: STATUS[ov.status || k.status], tagStyle: (ov.status || k.status) === 'working' ? '' : 'ghost',
      meta: [SHORT[d.id], `${sk.length} скиллов`], price: ov.task || k.task, sub: k.role,
      about: c.lead || k.role, features: sk.map(s => s.title), spec: (c.process || []).map(s => [s.t, s.d]),
      links: links(c.artifacts), works: pics(c).length,
      nums: [[String(sk.length), 'скиллов'], [String((c.process || []).length), 'шагов процесса'], [String(pics(c).length + (c.artifacts || []).length), 'готовых работ']],
      f: { dept: SHORT[d.id], kind: 'Агенты' },
    });
  }
}
// real task history of the office (tasks.js + tasks.auto.js) -> marquee; only tasks with a proof link
const MON = ['янв', 'фев', 'мар', 'апр', 'мая', 'июн', 'июл', 'авг', 'сен', 'окт', 'ноя', 'дек'];
const ru = d => { const [y, m, dd] = d.split('-'); return `${+dd} ${MON[m - 1]} ${y}`; };
const TASKS = [].concat(window.OFFICE_TASKS || [], (window.OFFICE_TASKS_AUTO || {}).tasks || [])
  .filter(t => t.date && t.title && (t.proof || []).length).sort((a, b) => b.date.localeCompare(a.date));
const marquee = TASKS.slice(0, 10).map(t => {
  // tile = the character who did the work, rendered from the office
  const who = (t.agents || []).find(id => CAT[id]), boss = (t.people || []).find(id => items.some(i => i.id === id));
  const label = t.proof[0].label.split(' · ')[0].slice(0, 42);
  return { text: t.title, name: SHORT[t.dept] || t.kind, sub: `${ru(t.date)} · ${label}`, url: t.proof[0].url,
    img: who ? `img/agent-${who}.jpg` : boss ? `img/head-${boss}.jpg` : '', mono: (SHORT[t.dept] || 'A')[0] };
});
const uniq = new Set(); Object.values(AC).forEach(c => (c.skills || []).forEach(k => uniq.add(k.name)));
const stats = { depts: CFG.depts.length, agents: items.filter(i => i.kind === 'agent').length, heads: CFG.depts.length,
  skills: uniq.size, tasks: TASKS.length };

const head = `/* GENERATED by _source/import-hq.js from apps/hq-office — do not edit by hand. */\n`;
const site = fs.readFileSync(path.join(__dirname, 'site-config.js'), 'utf8');
const data = {
  detailPage: 'agent.html',
  items, marquee, stats,
  filters: [
    { key: 'dept', label: 'Отдел', values: CFG.depts.map(d => SHORT[d.id]) },
    { key: 'kind', label: 'Кто', values: ['Руководители', 'Агенты'] },
  ],
};
fs.writeFileSync(path.join(__dirname, '../assets/data.js'), head + site + '\nwindow.SITE_DATA = ' + JSON.stringify(data, null, 1) + ';\n' +
  `window.SITE_DATA.sorts = { f: { label: 'Как в офисе', fn: null }, works: { label: 'Больше работ', fn: function (a, b) { return (b.works || 0) - (a.works || 0); } }, az: { label: 'По алфавиту', fn: function (a, b) { return a.name.localeCompare(b.name, 'ru'); } } };\n`);
console.log('data.js:', items.length, 'people/agents,', marquee.length, 'tasks in marquee', JSON.stringify(stats));
